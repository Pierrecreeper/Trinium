#!/usr/bin/env python3
"""Generate the typed Java/Rust GL wire contract. No game sources are included."""
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
# Java primitive ABI types; pointer offsets and addresses are longs, never retained.
SPECS=[
 ('glUseProgram','I'),('glBindVertexArray','I'),('glBindBuffer','II'),
 ('glEnable','I'),('glDisable','I'),('glEnablei','II'),('glDisablei','II'),
 ('glDepthFunc','I'),('glDepthMask','Z'),('glPolygonOffset','FF'),
 ('glColorMaski','IZZZZ'),('glBlendFuncSeparate','IIII'),('glBlendEquationSeparate','II'),
 ('glPolygonMode','II'),('glActiveTexture','I'),('glBindTexture','II'),
 ('glTexParameteri','III'),('glScissor','IIII'),('glBindBufferRange','IIIJJ'),
 ('glTexBuffer','III'),('glBindSampler','II'),('glBindVertexBuffer','IIJI'),
 ('glVertexAttribIPointer','IIIIJ'),('glVertexAttribPointer','IIIZIJ'),('glVertexAttribDivisor','II'),
 ('glDrawElementsInstancedBaseVertexBaseInstance','IIIJIII'),
 ('glDrawElementsInstancedBaseVertex','IIIJII'),
 ('glDrawArraysInstancedBaseInstance','IIIII'),('glDrawArraysInstanced','IIII'),
 ('nglMultiDrawArrays','IJJI'),('nglMultiDrawElementsBaseVertex','IJIJIJ'),
 ('glMultiDrawArraysIndirect','IJII'),('glDrawArraysIndirect','IJ'),
 ('glMultiDrawElementsIndirect','IIJII'),('glDrawElementsIndirect','IIJ'),
]
OWNERS={'glBindVertexBuffer':'ARBVertexAttribBinding','glDrawElementsInstancedBaseVertexBaseInstance':'ARBBaseInstance','glDrawArraysInstancedBaseInstance':'ARBBaseInstance','glMultiDrawArraysIndirect':'ARBMultiDrawIndirect','glMultiDrawElementsIndirect':'ARBMultiDrawIndirect','glDrawArraysIndirect':'ARBDrawIndirect','glDrawElementsIndirect':'ARBDrawIndirect'}
def owner(n): return OWNERS.get(n,'GL33C')
types={'I':'int','J':'long','F':'float','Z':'boolean'}
def params(s): return ', '.join(f'{types[t]} a{i}' for i,t in enumerate(s))
def args(s): return ', '.join(f'a{i}' for i in range(len(s)))
def wire(s):
 vals=[f'Float.floatToRawIntBits(a{i})' if t=='F' else f'(a{i} ? 1 : 0)' if t=='Z' else f'a{i}' for i,t in enumerate(s)]
 return vals
java='''package fr.pierrecreeper.trinium.graphics;

import org.lwjgl.opengl.*;
/** Generated by tools/generate-gl-driver.py. All pointer arguments live only until end(). */
public final class GlCommands {
    private GlCommands() { }
    public static final String[] FUNCTIONS = {
'''+''.join(f'        "{n.removeprefix("n")}",\n' for n,s in SPECS)+'''    };
'''
for op,(n,s) in enumerate(SPECS):
 writes=f'batch.storage.putLong(p, {op})'+''.join(f'.putLong(p+{(i+1)*8}, {v})' for i,v in enumerate(wire(s)))+';'
 java+=f'''    public static void {n}({params(s)}) {{
        RustGlDriver.State batch = RustGlDriver.command({op});
        if (batch == null) {{ {owner(n)}.{n}({args(s)}); return; }}
        int p = batch.offset;
        {writes}
    }}
'''
java+='}\n'
p=ROOT/'src/main/java/fr/pierrecreeper/trinium/graphics';p.mkdir(parents=True,exist_ok=True)
(p/'GlCommands.java').write_text(java)
# Redirect only commands that occur inside setup/draw. Outside a draw scope, execute LWJGL immediately.
groups={
 'GlStateCommandsMixin':('com.mojang.renderpearl.backend.opengl.GlStateManager',[n for n,s in SPECS[:18] if n not in ['glEnable','glDisable']]),
 'GlBooleanCommandsMixin':('com.mojang.renderpearl.backend.opengl.GlStateManager$BooleanState',['glEnable','glDisable']),
 'GlEncoderCommandsMixin':('com.mojang.renderpearl.backend.opengl.GlCommandEncoder',['glBindTexture','glBindBufferRange','glTexBuffer','glBindSampler']+[n for n,s in SPECS[25:]]),
 'GlVertexCommandsMixin':('com.mojang.renderpearl.backend.opengl.VertexArray$Separate',['glBindVertexBuffer']),
 'GlLegacyVertexCommandsMixin':('com.mojang.renderpearl.backend.opengl.VertexArray$Emulated',['glVertexAttribIPointer','glVertexAttribPointer','glVertexAttribDivisor'])
}
p=ROOT/'src/main/java/fr/pierrecreeper/trinium/mixin'
for cls,(target,names) in groups.items():
 text=f'''package fr.pierrecreeper.trinium.mixin;

import fr.pierrecreeper.trinium.graphics.GlCommands;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.*;
/** Generated by tools/generate-gl-driver.py. */
@Mixin(targets = "{target}", remap = false)
public abstract class {cls} {{
'''
 for n,s in SPECS:
  if n not in names:continue
  static='static ' if cls=='GlStateCommandsMixin' else ''
  method='bind' if 'VertexCommands' in cls else '*'
  text+=f'''    @Redirect(method = "{method}", at = @At(value = "INVOKE", target = "Lorg/lwjgl/opengl/{owner(n)};{n}({s})V"))
    private {static}void trinium${n}({params(s)}) {{ GlCommands.{n}({args(s)}); }}
'''
 (p/(cls+'.java')).write_text(text+'}\n')
# Typed native dispatch. All inputs are validated before any function is invoked.
rust='''// Generated by tools/generate-gl-driver.py. OpenGL APIENTRY is extern system.
pub const FUNCTION_COUNT: usize = '''+str(len(SPECS))+''';
pub unsafe fn dispatch(op: usize, function: usize, a: &[u64; 7]) {
    match op {
'''
rt={'I':'u32','J':'usize','F':'f32','Z':'u8'}
for op,(n,s) in enumerate(SPECS):
 ts=', '.join(rt[t] for t in s)
 vs=', '.join(f'f32::from_bits(a[{i}] as u32)' if t=='F' else f'a[{i}] as {rt[t]}' for i,t in enumerate(s))
 rust+=f'''        {op} => {{ // {n}
            let f: unsafe extern "system" fn({ts}) = unsafe {{ std::mem::transmute(function) }};
            unsafe {{ f({vs}) }};
        }}
'''
rust+='        _ => unreachable!("validated opcode"),\n    }\n}\n'
(ROOT/'native/src/gl_dispatch.rs').write_text(rust)

# Keep the committed generated dispatch reproducible under cargo fmt.
import subprocess
subprocess.run(["rustfmt", "--edition", "2021", str(ROOT/"native/src/gl_dispatch.rs")],check=True)
